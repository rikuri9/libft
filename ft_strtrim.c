#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*t_str;
	size_t	start;
	size_t	end;

	if (!s1 || !set)
		return (NULL);
	start = 0;
	while (s1[start] && ft_strchr(set, s1[start]))
		start++;
	end = ft_strlen(s1);
	while (start < end && ft_strchr(set, s1[end - 1]))
		end--;
	t_str = (char *)malloc(sizeof(char) * (end - start + 1));
	if (!t_str)
		return (NULL);
	ft_memcpy(t_str, s1 + start, end - start);
	t_str[end - start] = '\0';
	return (t_str);
}
